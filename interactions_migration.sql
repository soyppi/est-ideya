-- Replies and private status notifications. Apply to an existing installation.
begin;
alter table public.comments add column if not exists reply_to_id bigint references public.comments(id) on delete set null;
create index if not exists comments_reply_idx on public.comments(reply_to_id);
create or replace function public.validate_comment_reply()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.reply_to_id is not null and (tg_op='INSERT' or new.reply_to_id is distinct from old.reply_to_id or new.idea_id is distinct from old.idea_id) then
  perform 1 from public.comments where id=new.reply_to_id and idea_id=new.idea_id and deleted_at is null for share;
  if not found then raise exception 'Сообщение для ответа скрыто или относится к другой идее.'; end if;
  if new.reply_to_id=new.id then raise exception 'Нельзя ответить на это же сообщение.'; end if;
 end if;
 return new;
end; $$;
drop trigger if exists validate_comment_reply on public.comments;
create trigger validate_comment_reply before insert or update of reply_to_id,idea_id on public.comments for each row execute function public.validate_comment_reply();
create or replace function public.submit_comment_reply(p_request_id uuid,p_idea_id bigint,p_body text,p_reply_to_id bigint)
returns bigint language plpgsql security definer set search_path=public as $$
declare result bigint;
begin
 if auth.uid() is null then raise exception 'Войди в аккаунт.'; end if;
 if p_request_id is null then raise exception 'Не указан идентификатор запроса.'; end if;
 perform 1 from public.ideas where id=p_idea_id and deleted_at is null for share;
 if not found then raise exception 'Идея не найдена.'; end if;
 select id into result from public.comments where user_id=auth.uid() and request_id=p_request_id and idea_id=p_idea_id;
 if result is not null then return result; end if;
 insert into public.comments(user_id,idea_id,body,request_id,reply_to_id)
 values(auth.uid(),p_idea_id,trim(p_body),p_request_id,p_reply_to_id)
 on conflict(user_id,request_id) do nothing returning id into result;
 if result is null then select id into result from public.comments where user_id=auth.uid() and request_id=p_request_id and idea_id=p_idea_id; end if;
 if result is null then raise exception 'Идентификатор запроса уже используется для другой идеи.'; end if;
 return result;
end; $$;
revoke all on function public.validate_comment_reply() from public,anon,authenticated;
revoke all on function public.submit_comment_reply(uuid,bigint,text,bigint) from public,anon,authenticated;
grant execute on function public.submit_comment_reply(uuid,bigint,text,bigint) to authenticated;

create table if not exists public.notifications (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 idea_id bigint not null references public.ideas(id) on delete cascade,
 history_id bigint not null unique references public.status_history(id) on delete cascade,
 idea_title text not null,
 from_status text,
 to_status text not null,
 reason text not null,
 created_at timestamptz not null default now(),
 read_at timestamptz
);
create index if not exists notifications_user_created_idx on public.notifications(user_id,created_at desc,id desc);
create index if not exists notifications_unread_idx on public.notifications(user_id) where read_at is null;
alter table public.notifications enable row level security;
revoke all on public.notifications from public,anon,authenticated;
revoke all on sequence public.notifications_id_seq from public,anon,authenticated;
grant select on public.notifications to authenticated;
grant update(read_at) on public.notifications to authenticated;
drop policy if exists "read own notifications" on public.notifications;
create policy "read own notifications" on public.notifications for select to authenticated using (user_id=auth.uid());
drop policy if exists "mark own notifications read" on public.notifications;
create policy "mark own notifications read" on public.notifications for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());
create or replace function public.notify_idea_author()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.from_status is distinct from new.to_status then
  insert into public.notifications(user_id,idea_id,history_id,idea_title,from_status,to_status,reason)
  select i.user_id,i.id,new.id,i.title,new.from_status,new.to_status,new.reason from public.ideas i where i.id=new.idea_id
  on conflict(history_id) do nothing;
 end if;
 return new;
end; $$;
revoke all on function public.notify_idea_author() from public,anon,authenticated;
drop trigger if exists notify_idea_author on public.status_history;
create trigger notify_idea_author after insert on public.status_history for each row execute function public.notify_idea_author();
commit;
