-- Schema for "Есть идея" on GitHub Pages + Supabase.
-- Run the entire file in Supabase SQL Editor. Never put service_role keys in browser code.
begin;
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Участник',
  role text not null default 'user' check (role in ('user','moderator')),
  created_at timestamptz not null default now()
);

create table if not exists public.ideas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  title text not null check (char_length(trim(title)) between 3 and 120),
  problem text not null check (char_length(trim(problem)) > 0),
  solution text not null check (char_length(trim(solution)) > 0),
  category text not null default 'Другое',
  status text not null default 'Новое' check (status in ('Новое','На рассмотрении','Принято','Отклонено','Реализовано')),
  created_at timestamptz not null default now(),
  deleted_at timestamptz,
  deleted_reason text,
  deleted_by uuid references public.profiles(id)
);

create table if not exists public.votes (
  user_id uuid not null references public.profiles(id) on delete cascade,
  idea_id bigint not null references public.ideas(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, idea_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  idea_id bigint not null references public.ideas(id) on delete cascade,
  body text not null check (char_length(trim(body)) > 0),
  created_at timestamptz not null default now(),
  deleted_at timestamptz,
  deleted_reason text,
  deleted_by uuid references public.profiles(id)
);

create table if not exists public.status_history (
  id bigint generated by default as identity primary key,
  idea_id bigint not null references public.ideas(id) on delete cascade,
  from_status text,
  to_status text not null,
  reason text not null check (char_length(trim(reason)) > 0),
  moderator_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create index if not exists ideas_created_idx on public.ideas(created_at desc);
create index if not exists ideas_status_idx on public.ideas(status);
create index if not exists comments_idea_idx on public.comments(idea_id);
create index if not exists history_idea_idx on public.status_history(idea_id, created_at);

-- Keep defaults and status validation consistent when reapplying the schema.
alter table public.profiles alter column name set default 'Участник';
alter table public.ideas alter column category set default 'Другое';
alter table public.ideas alter column status set default 'Новое';
alter table public.ideas drop constraint if exists ideas_status_check;
alter table public.ideas add constraint ideas_status_check
  check (status in ('Новое','На рассмотрении','Принято','Отклонено','Реализовано'));

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, role)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), 'Участник'), 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_moderator()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'moderator'); $$;

alter table public.profiles enable row level security;
alter table public.ideas enable row level security;
alter table public.votes enable row level security;
alter table public.comments enable row level security;
alter table public.status_history enable row level security;

drop policy if exists "profiles readable by signed in users" on public.profiles;
drop policy if exists "public profile names readable" on public.profiles;
create policy "public profile names readable" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "user updates own name only" on public.profiles;
create policy "user updates own name only" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
-- No direct insert/delete on profiles: trigger creates users and role changes are moderator-only SQL administration.

drop policy if exists "published ideas readable" on public.ideas;
create policy "published ideas readable" on public.ideas for select to anon, authenticated using (deleted_at is null or public.is_moderator());
drop policy if exists "create own idea" on public.ideas;
create policy "create own idea" on public.ideas for insert to authenticated with check (user_id = auth.uid() and status = 'Новое' and deleted_at is null);
drop policy if exists "edit own new idea" on public.ideas;
create policy "edit own new idea" on public.ideas for update to authenticated using (user_id = auth.uid() and status = 'Новое' and deleted_at is null) with check (user_id = auth.uid() and status = 'Новое' and deleted_at is null);
-- Status and deletion updates are performed only through security-definer RPC functions.

drop policy if exists "votes readable" on public.votes;
create policy "votes readable" on public.votes for select to anon, authenticated using (exists(select 1 from public.ideas i where i.id = idea_id and i.deleted_at is null));
drop policy if exists "vote on visible idea" on public.votes;
create policy "vote on visible idea" on public.votes for insert to authenticated with check (user_id = auth.uid() and exists(select 1 from public.ideas i where i.id = idea_id and i.deleted_at is null));
drop policy if exists "remove own vote" on public.votes;
create policy "remove own vote" on public.votes for delete to authenticated using (user_id = auth.uid());

drop policy if exists "visible comments readable" on public.comments;
create policy "visible comments readable" on public.comments for select to anon, authenticated using ((deleted_at is null and exists(select 1 from public.ideas i where i.id = idea_id and i.deleted_at is null)) or public.is_moderator());
drop policy if exists "comment on visible idea" on public.comments;
create policy "comment on visible idea" on public.comments for insert to authenticated with check (user_id = auth.uid() and deleted_at is null and exists(select 1 from public.ideas i where i.id = idea_id and i.deleted_at is null));

drop policy if exists "visible idea history readable" on public.status_history;
create policy "visible idea history readable" on public.status_history for select to anon, authenticated using (exists(select 1 from public.ideas i where i.id = idea_id and (i.deleted_at is null or public.is_moderator())));

create or replace function public.change_idea_status(p_idea_id bigint, p_new_status text, p_reason text)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare v_idea public.ideas%rowtype; v_role text;
begin
  select role into v_role from public.profiles where id = auth.uid();
  if v_role is distinct from 'moderator' then raise exception 'Недостаточно прав.'; end if;
  if p_reason is null or length(trim(p_reason)) = 0 then raise exception 'Укажи объяснение решения.'; end if;
  select * into v_idea from public.ideas where id = p_idea_id for update;
  if not found or v_idea.deleted_at is not null then raise exception 'Идея не найдена.'; end if;
  if v_idea.status = p_new_status then return jsonb_build_object('changed', false, 'status', v_idea.status); end if;
  if not ((v_idea.status = 'Новое' and p_new_status = 'На рассмотрении') or
          (v_idea.status = 'На рассмотрении' and p_new_status in ('Принято','Отклонено')) or
          (v_idea.status = 'Принято' and p_new_status in ('Реализовано','Отклонено'))) then
    raise exception 'Такой переход статуса запрещён.';
  end if;
  update public.ideas set status = p_new_status where id = p_idea_id;
  insert into public.status_history(idea_id, from_status, to_status, reason, moderator_id)
  values (p_idea_id, v_idea.status, p_new_status, trim(p_reason), auth.uid());
  return jsonb_build_object('changed', true, 'status', p_new_status);
end;
$$;

create or replace function public.moderator_delete_idea(p_idea_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_moderator() then raise exception 'Недостаточно прав.'; end if;
  if p_reason is null or length(trim(p_reason)) = 0 then raise exception 'Укажи причину удаления.'; end if;
  update public.ideas set deleted_at = coalesce(deleted_at, now()), deleted_reason = trim(p_reason), deleted_by = auth.uid()
  where id = p_idea_id;
  if not found then raise exception 'Идея не найдена.'; end if;
end;
$$;

create or replace function public.moderator_delete_comment(p_comment_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_moderator() then raise exception 'Недостаточно прав.'; end if;
  if p_reason is null or length(trim(p_reason)) = 0 then raise exception 'Укажи причину удаления.'; end if;
  update public.comments set deleted_at = coalesce(deleted_at, now()), deleted_reason = trim(p_reason), deleted_by = auth.uid()
  where id = p_comment_id;
  if not found then raise exception 'Комментарий не найден.'; end if;
end;
$$;

create or replace function public.moderator_restore_idea(p_idea_id bigint)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_moderator() then raise exception 'Недостаточно прав.'; end if;
  update public.ideas set deleted_at = null, deleted_reason = null, deleted_by = null where id = p_idea_id;
  if not found then raise exception 'Идея не найдена.'; end if;
end;
$$;

-- Supabase can grant table-wide privileges by default. Reset them first:
-- a column-level GRANT alone does not remove an existing table-wide UPDATE.
revoke all privileges on public.profiles, public.ideas, public.votes, public.comments, public.status_history from public, anon, authenticated;
revoke update (name, role, created_at, id) on public.profiles from public, anon, authenticated;
revoke update (id, user_id, title, problem, solution, category, status, created_at, deleted_at, deleted_reason, deleted_by) on public.ideas from public, anon, authenticated;
revoke all privileges on sequence public.ideas_id_seq, public.comments_id_seq, public.status_history_id_seq from public, anon, authenticated;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.is_moderator() from public, anon, authenticated;
revoke execute on function public.change_idea_status(bigint,text,text) from public, anon, authenticated;
revoke execute on function public.moderator_delete_idea(bigint,text) from public, anon, authenticated;
revoke execute on function public.moderator_delete_comment(bigint,text) from public, anon, authenticated;
revoke execute on function public.moderator_restore_idea(bigint) from public, anon, authenticated;

grant usage on schema public to anon, authenticated;
grant select on public.profiles, public.ideas, public.votes, public.comments, public.status_history to anon, authenticated;
grant insert on public.ideas, public.comments to authenticated;
grant update (name) on public.profiles to authenticated;
grant update (title, problem, solution, category) on public.ideas to authenticated;
grant insert, delete on public.votes to authenticated;
grant usage on sequence public.ideas_id_seq, public.comments_id_seq to authenticated;
grant execute on function public.is_moderator() to anon, authenticated;
grant execute on function public.change_idea_status(bigint,text,text) to authenticated;
grant execute on function public.moderator_delete_idea(bigint,text) to authenticated;
grant execute on function public.moderator_delete_comment(bigint,text) to authenticated;
grant execute on function public.moderator_restore_idea(bigint) to authenticated;

commit;
